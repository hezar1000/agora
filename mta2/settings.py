# SAML2 authentication
SAML2_INTEGRATION_ENABLED = env_bool("SAML2_INTEGRATION_ENABLED", False)
if SAML2_INTEGRATION_ENABLED:
    LOGIN_URL = "account:login"
    from .saml_settings import *

    # form-action is enforced against redirect targets, not just a form's own
    # action. Sign-in posts here and is then redirected to the identity
    # provider, so without the provider's origin the browser blocks that
    # navigation silently: the button appears to do nothing and the only trace
    # is a console violation. Derived from the configured provider rather than
    # hard-coded, so another deployment allows its own and nothing more.
    from urllib.parse import urlsplit as _urlsplit

    def _provider_origins(providers):
        """Origins the provider will redirect the browser to, from its config."""
        origins = set()
        for provider in (providers or {}).values():
            idp = (provider or {}).get("idp") or {}
            for service in ("singleSignOnService", "singleLogoutService"):
                url = (idp.get(service) or {}).get("url", "")
                parts = _urlsplit(url)
                if parts.scheme in {"https", "http"} and parts.netloc:
                    origins.add("%s://%s" % (parts.scheme, parts.netloc))
        return sorted(origins)

    _idp_origins = _provider_origins(globals().get("SAML_PROVIDERS"))
    if _idp_origins:
        _CSP_DIRECTIVES = [
            "%s %s" % (directive, " ".join(_idp_origins))
            if directive.startswith("form-action ")
            else directive
            for directive in _CSP_DIRECTIVES
        ]
else:
    LOGIN_URL = "account:login"

CONTENT_SECURITY_POLICY = "; ".join(_CSP_DIRECTIVES)


