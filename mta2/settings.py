def csrf_trusted_origins_for_hosts(allowed_hosts):
    raw_origins = required_setting(
        "DJANGO_CSRF_TRUSTED_ORIGINS",
        "http://localhost,http://127.0.0.1",
    )
    origins = [origin.strip().rstrip("/") for origin in raw_origins.split(",")]
    origins = [origin for origin in origins if origin]
    if not origins:
        raise ImproperlyConfigured(
            "DJANGO_CSRF_TRUSTED_ORIGINS must contain at least one origin."
        )

    allowed_host_set = set(allowed_hosts)
    for origin in origins:
        parsed = urlsplit(origin)
        if (
            parsed.scheme not in {"http", "https"}
            or not parsed.hostname
            or parsed.username
            or parsed.password
            or parsed.path
            or parsed.query
            or parsed.fragment
        ):
            raise ImproperlyConfigured(
                "DJANGO_CSRF_TRUSTED_ORIGINS must contain origins only."
            )
        if not ALLOW_INSECURE_LOCAL_DEFAULTS and parsed.scheme != "https":
            raise ImproperlyConfigured(
                "Production CSRF trusted origins must use HTTPS."
            )
        if parsed.hostname not in allowed_host_set:
            raise ImproperlyConfigured(
                "Every CSRF trusted origin hostname must be in DJANGO_ALLOWED_HOSTS."
            )
    return origins


