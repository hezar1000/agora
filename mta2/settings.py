def build_email_configuration():
    backend = os.environ.get(
        "DJANGO_EMAIL_BACKEND",
        "django.core.mail.backends.console.EmailBackend"
        if ALLOW_INSECURE_LOCAL_DEFAULTS
        else SMTP_EMAIL_BACKEND,
    )
    default_from = required_setting("DEFAULT_FROM_EMAIL", "webmaster@localhost")
    configuration = {
        "backend": backend,
        "default_from": default_from,
        "host": os.environ.get("EMAIL_HOST", ""),
        "port": 25,
        "use_tls": False,
        "username": os.environ.get("EMAIL_HOST_USER", ""),
        "password": os.environ.get("EMAIL_HOST_PASSWORD", ""),
    }
    if backend != SMTP_EMAIL_BACKEND:
        return configuration

    configuration["host"] = required_setting("EMAIL_HOST")
    configuration["username"] = required_setting("EMAIL_HOST_USER")
    configuration["password"] = required_setting("EMAIL_HOST_PASSWORD")
    raw_port = required_setting("EMAIL_PORT")
    try:
        configuration["port"] = int(raw_port)
    except ValueError as exc:
        raise ImproperlyConfigured("EMAIL_PORT must be a valid TCP port.") from exc
    if not 1 <= configuration["port"] <= 65535:
        raise ImproperlyConfigured("EMAIL_PORT must be a valid TCP port.")

    raw_tls = required_setting("EMAIL_USE_TLS").strip().lower()
    if raw_tls not in {"1", "true", "yes", "on", "0", "false", "no", "off"}:
        raise ImproperlyConfigured("EMAIL_USE_TLS must be an explicit boolean.")
    configuration["use_tls"] = raw_tls in {"1", "true", "yes", "on"}
    return configuration


