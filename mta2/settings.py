# Persistent per-thread connections (CONN_MAX_AGE > 0) leak under ASGI: Daphne
# runs sync views on executor threads, each thread pins its own connection, and
# Django only closes aged connections on the thread that handles the next
# request. Threads that go quiet keep their connection open forever, so under
# lecture polling load the worker pool accumulated idle connections until
# PostgreSQL's connection slots ran out and every request 500'd
# (observed 2026-09-11 during AI100). A server-side psycopg pool caps the
# number of connections per worker instead; when it is active CONN_MAX_AGE
# must be 0 (Django refuses the combination).
_use_database_pool = (
    _database_pool_enabled()
    and DATABASES["default"]["ENGINE"] == "django.db.backends.postgresql"
)
if _use_database_pool:
    try:
        import psycopg_pool  # noqa: F401
    except ImportError:
        _use_database_pool = False

if _use_database_pool:
    DATABASES["default"].setdefault("OPTIONS", {})["pool"] = {
        "min_size": 2,
        # Four workers times this cap must stay comfortably under PostgreSQL's
        # max_connections (100), leaving slots for cron jobs and psql.
        "max_size": int(os.environ.get("DATABASE_POOL_MAX_SIZE", "18")),
        "timeout": 10,
    }
    DATABASES["default"].update(
        {
            "CONN_MAX_AGE": 0,
            "CONN_HEALTH_CHECKS": False,
        }
    )
else:
    DATABASES["default"].update(
        {
            "CONN_MAX_AGE": DATABASE_CONN_MAX_AGE,
            "CONN_HEALTH_CHECKS": DATABASE_CONN_MAX_AGE > 0,
        }
    )


